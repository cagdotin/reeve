// Writes packages/contract/src/routes.gen.ts: each operation's HTTP method and path, so the browser
// can call operations by name without loading the catalog's schemas.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { availableCatalog } from "../packages/contract/src/catalog.ts";

const routes = Object.fromEntries(
  Object.entries(availableCatalog()).map(([name, operation]) => [
    name,
    [operation.http.method, `/api${operation.http.path}`],
  ]),
);

writeFileSync(
  join(import.meta.dirname, "../packages/contract/src/routes.gen.ts"),
  `// Generated by scripts/routes.ts from the catalog; do not edit.
export const routes = ${JSON.stringify(routes, null, 2)} as const;
`,
);
console.log(`Wrote ${Object.keys(routes).length} routes`);
