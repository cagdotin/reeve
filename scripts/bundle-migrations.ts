// Writes packages/engine/src/db/migrations.gen.ts from drizzle-kit's migration folders, so the
// engine carries its migrations as code: the CLI, the server and the desktop bundle need no files.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "../packages/engine/drizzle");
const migrations = readdirSync(root, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .toSorted()
  .map((name) => ({ name, sql: readFileSync(join(root, name, "migration.sql"), "utf8") }));

writeFileSync(
  join(import.meta.dirname, "../packages/engine/src/db/migrations.gen.ts"),
  `// Generated by scripts/bundle-migrations.ts from packages/engine/drizzle; do not edit.
export const migrations: ReadonlyArray<{ readonly name: string; readonly sql: string }> = ${JSON.stringify(migrations, null, 2)};
`,
);
console.log(`Bundled ${migrations.length} migrations`);
